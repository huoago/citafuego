-- CitaFuego V12.1: atomic rate limits for the pre-auth account Edge Function.
create table if not exists public.account_auth_rate_limits (
  id bigint generated by default as identity primary key,
  action text not null check (action in ('register_ip','login_ip','login_account')),
  fingerprint text not null check (char_length(fingerprint) between 32 and 128),
  created_at timestamptz not null default now()
);

create index if not exists account_auth_rate_limits_lookup_idx
  on public.account_auth_rate_limits(action,fingerprint,created_at desc);

alter table public.account_auth_rate_limits enable row level security;
revoke all on table public.account_auth_rate_limits from public,anon,authenticated;
grant select,insert,delete on table public.account_auth_rate_limits to service_role;

create or replace function public.consume_account_auth_rate_limit(
  p_action text,
  p_fingerprint text,
  p_limit integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_count integer;
begin
  if p_action not in ('register_ip','login_ip','login_account')
     or char_length(p_fingerprint) not between 32 and 128
     or p_limit < 1 or p_limit > 100
     or p_window_seconds < 60 or p_window_seconds > 86400 then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_action || ':' || p_fingerprint,0));

  delete from public.account_auth_rate_limits
  where created_at < now() - interval '1 day';

  select count(*) into v_count
  from public.account_auth_rate_limits
  where action=p_action
    and fingerprint=p_fingerprint
    and created_at >= now() - make_interval(secs => p_window_seconds);

  if v_count >= p_limit then return false; end if;

  insert into public.account_auth_rate_limits(action,fingerprint)
  values(p_action,p_fingerprint);
  return true;
end;
$$;

revoke all on function public.consume_account_auth_rate_limit(text,text,integer,integer) from public,anon,authenticated;
grant execute on function public.consume_account_auth_rate_limit(text,text,integer,integer) to service_role;
